import { isStudioDocument, type StudioDocument, type StudioNode } from "./schema";
const quoted=(s:string)=>JSON.stringify(s);
function render(n:StudioNode,i:number):string{
 const style=`{position:"absolute",left:${n.x},top:${n.y}${n.width===undefined?"":`,width:${n.width}`}${n.height===undefined?"":`,height:${n.height}`}}`;
 const label=quoted(n.label);
 switch(n.type){
  case "Icon":return `<Text style={${style}}>✦</Text>`;
  case "Text":return `<Text style={${style}}>${"{"+label+"}"}</Text>`;
  case "Button":return `<Pressable accessibilityRole="button" accessibilityLabel={${quoted(n.accessibilityLabel||n.label)}} onPress={() => { /* TODO */ }} style={${style}}><Text>{${label}}</Text></Pressable>`;
  case "TextField":return `<TextInput accessibilityLabel={${quoted(n.accessibilityLabel||n.label)}} placeholder={${label}} style={${style}} />`;
  case "Switch":return `<Switch accessibilityLabel={${quoted(n.accessibilityLabel||n.label)}} value={states[${i}] ?? false} onValueChange={v=>setStates(s=>({...s,[${i}]:v}))} style={${style}} />`;
  case "Checkbox":return `<Pressable accessibilityRole="checkbox" accessibilityState={{checked:states[${i}]??false}} onPress={()=>setStates(s=>({...s,[${i}]:!s[${i}]}))} style={${style}}><Text>☑ {${label}}</Text></Pressable>`;
  case "Card":case "Frame":case "Rectangle":return `<View style={${style}}><Text>{${label}}</Text></View>`;
 }
}
export function exportReactNative(doc:StudioDocument):string{
 if(!isStudioDocument(doc))throw Error("Invalid project");
 return `// Experimental React Native / Expo screen generated by DroidUI.
// Add this TSX file to an existing React Native or Expo project.
// Absolute coordinates are not responsive; integrate navigation and actions manually.
import React, {useState} from "react";
import {View,Text,TextInput,Pressable,Switch} from "react-native";
export default function DroidUIScreen(){
 const [states,setStates]=useState<Record<number,boolean>>({});
 return <View style={{flex:1,backgroundColor:"#ffffff"}}>
${doc.nodes.map((n,i)=>"  "+render(n,i)).join("\n")}
 </View>;
}
`;
}
