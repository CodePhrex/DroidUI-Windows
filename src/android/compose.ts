import type { StudioDocument, StudioNode } from "./schema";
import { isStudioDocument } from "./schema";

const kt = (value: string) => JSON.stringify(value).replace(/\$/g, "\\$");
const safeNumber = (n:number) => Math.max(0,Math.min(10000,Math.round(n*100)/100));
const dp = (n:number) => `${safeNumber(n)}.dp`;
const sp = (n:number) => `${Math.max(8,Math.min(96,safeNumber(n)))}.sp`;
const ident = (name:string) => {
  const cleaned=name.replace(/[^a-zA-Z0-9_]/g,"_").replace(/^([^a-zA-Z_])/,"_$1");
  return cleaned || "DroidUI";
};
const modifier = (node:StudioNode) => {
  const mods = [`Modifier.offset(x = ${dp(node.x)}, y = ${dp(node.y)})`];
  if (node.width !== undefined) mods.push(`.width(${dp(node.width)})`);
  if (node.height !== undefined) mods.push(`.height(${dp(node.height)})`);
  if (node.accessibilityLabel) mods.push(`.semantics { contentDescription = ${kt(node.accessibilityLabel)} }`);
  return mods.join("");
};
function render(node:StudioNode, index:number):string {
  const m=modifier(node), label=kt(node.label);
  switch(node.type) {
    case "Text": return `Text(text = ${label}, modifier = ${m}, fontSize = ${sp(node.fontSizeSp ?? 16)})`;
    case "Button": return `Button(onClick = { /* TODO: connect app action */ }, modifier = ${m}) { Text(${label}) }`;
    case "TextField": return `var field${index} by remember { mutableStateOf("") }
TextField(value = field${index}, onValueChange = { field${index} = it }, label = { Text(${label}) }, modifier = ${m})`;
    case "Switch": return `var checked${index} by remember { mutableStateOf(false) }
Switch(checked = checked${index}, onCheckedChange = { checked${index} = it }, modifier = ${m})`;
    case "Checkbox": return `var checked${index} by remember { mutableStateOf(false) }
Checkbox(checked = checked${index}, onCheckedChange = { checked${index} = it }, modifier = ${m})`;
    case "Card": return `Card(modifier = ${m}) { Text(${label}, modifier = Modifier.padding(16.dp)) }`;
    case "Rectangle": return `Box(modifier = ${m}.background(Color(0xFF7AA9E8)))`;
    case "Frame": return `Box(modifier = ${m}.border(1.dp, Color(0xFF5B8BC8))) { Text(${label}) }`;
  }
}
export function exportCompose(doc: StudioDocument): string {
  if (!isStudioDocument(doc)) throw new Error("Invalid desktop project. Export cancelled.");
  const name=ident(doc.name);
  const body=doc.nodes.map((node,i)=>render(node,i).split("\n").map(line=>"    "+line).join("\n")).join("\n\n");
  return `// Generated by DroidUI Desktop — experimental Compose export.
// Requires an Android project with Jetpack Compose and Material 3 dependencies.
// Coordinates are absolute dp offsets, not responsive constraints.
// Replace TODO actions and test accessibility and layouts on a real device.
import androidx.compose.foundation.background
import androidx.compose.foundation.border
import androidx.compose.foundation.layout.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.semantics.contentDescription
import androidx.compose.ui.semantics.semantics
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

@Composable
fun ${name}Screen() {
  Box(modifier = Modifier.fillMaxSize()) {
${body}
  }
}
`;
}
