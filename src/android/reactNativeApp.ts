import {isStudioDocument,type StudioDocument,type StudioNode} from "./schema";
const quote=(s:string)=>JSON.stringify(s);
function render(n:StudioNode,i:number):string{
 const style=`{position:"absolute",left:${n.x},top:${n.y}${n.width===undefined?"":`,width:${n.width}`}${n.height===undefined?"":`,height:${n.height}`}}`;
 const label=quote(n.label);
 const go=n.navigateTo?`onNavigate(${quote(n.navigateTo)})`:"undefined";
 switch(n.type){
 case "Text":return `<Text style={${style}}>{${label}}</Text>`;
 case "Icon":return `<Text style={${style}} accessibilityLabel={${quote(n.accessibilityLabel||n.iconName||"icon")}}>✦</Text>`;
 case "Button":return `<Pressable accessibilityRole="button" accessibilityLabel={${quote(n.accessibilityLabel||n.label)}} onPress={()=>{${go}}} style={${style}}><Text>{${label}}</Text></Pressable>`;
 case "TextField":return `<TextInput accessibilityLabel={${quote(n.accessibilityLabel||n.label)}} placeholder={${label}} style={${style}} />`;
 case "Switch":return `<Switch value={states[${i}]??false} onValueChange={v=>setStates(s=>({...s,[${i}]:v}))} style={${style}} />`;
 case "Checkbox":return `<Pressable accessibilityRole="checkbox" accessibilityState={{checked:states[${i}]??false}} onPress={()=>setStates(s=>({...s,[${i}]:!s[${i}]}))} style={${style}}><Text>{${label}}</Text></Pressable>`;
 default:return `<View style={${style}}><Text>{${label}}</Text></View>`;
 }
}
export function exportReactNativeApp(screens:StudioDocument[]):string{
 if(!screens.length||!screens.every(isStudioDocument))throw Error("Invalid screens");
 const names=screens.map(s=>s.name);
 if(new Set(names).size!==names.length)throw Error("Screen names must be unique for navigation");
 const cases=screens.map((screen,i)=>`case ${quote(screen.name)}: return <Screen${i} onNavigate={setCurrent}/>;`).join("\n   ");
 const definitions=screens.map((screen,i)=>`function Screen${i}({onNavigate}:{onNavigate:(screen:string)=>void}) {
 const [states,setStates]=useState<Record<number,boolean>>({});
 return <View style={{flex:1,backgroundColor:"#ffffff"}}>
 ${screen.nodes.map((n,j)=>render(n,j)).join("\n ")}
 </View>;
}`).join("\n\n");
 return `// Generated by DroidUI Professional Studio — experimental multi-screen React Native source.
// Add to an existing Expo/React Native project. This is not a standalone APK project.
// Absolute dp coordinates are not responsive; vector icons are placeholders.
// Navigation is in-memory screen switching, not deep linking or a navigation library.
import React,{useState} from "react";
import {View,Text,TextInput,Pressable,Switch} from "react-native";

${definitions}

export default function DroidUIApp(){
 const [current,setCurrent]=useState(${quote(screens[0].name)});
 switch(current){
   ${cases}
   default:return <Screen0 onNavigate={setCurrent}/>;
 }
}
`;
}
